/** How the current level compares with the highest flood level (HFL) ever recorded at the gauge */
export function calculateHFLComparison(
  currentValue: number,
  hfl: number
): {
  isSurpassedHFL: boolean;
  differenceToHFL: number;
  hflMarginPercent: number;
  hflStatusText: string;
} {
  const diffToHfl = Math.round((hfl - currentValue) * 100) / 100;
  const isSurpassed = currentValue >= hfl;
  const hflMarginPercent = Math.min(100, Math.max(0, (currentValue / hfl) * 100));

  return {
    isSurpassedHFL: isSurpassed,
    differenceToHFL: diffToHfl,
    hflMarginPercent: Math.round(hflMarginPercent * 10) / 10,
    hflStatusText: isSurpassed
      ? `SURPASSED HFL by ${(currentValue - hfl).toFixed(2)}m`
      : `${diffToHfl.toFixed(2)}m below historical HFL`,
  };
}


/**
 * Normal below the warning mark, Watch from the warning mark, Danger from the danger mark. Always
 * show the returned label alongside any colour: status must never rely on colour alone.
 */
export function calculateStationSeverity(
  value: number,
  warningLevel: number,
  dangerLevel: number
): {
  level: "normal" | "watch" | "danger";
  label: string;
  statusText: string;
  differenceToDanger: number;
} {
  const diff = Math.round((dangerLevel - value) * 100) / 100;
  if (value >= dangerLevel) {
    return {
      level: "danger",
      label: "Danger",
      statusText: `${Math.abs(diff)}m ABOVE Danger Level`,
      differenceToDanger: diff,
    };
  }
  if (value >= warningLevel) {
    return {
      level: "watch",
      label: "Watch",
      statusText: `${diff}m below Danger (Warning Active)`,
      differenceToDanger: diff,
    };
  }
  return {
    level: "normal",
    label: "Normal",
    statusText: `${diff}m below Danger Level`,
    differenceToDanger: diff,
  };
}


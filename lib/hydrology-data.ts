// The website's built-in pilot data: districts, gauge stations, reservoirs and river basins in
// Bihar and Assam, plus the helpers that turn a reading into a status.
//
// Every level and reading in this file is illustrative sample data. Pages show it straight away
// and then swap in live values from Firestore (gaugeStations, reservoirs, districts) when they
// exist. functions/src/seedPilotData.ts holds the matching Firestore seed.

export interface HelplineContact {
  title: string;
  number: string;
  type: "state_control_room" | "district_disaster_authority" | "ndrf_sdrf" | "toll_free";
}

export interface DistrictData {
  id: string;
  slug: string;
  name: string;
  state: "Bihar" | "Assam";
  latitude: number;
  longitude: number;
  helplineNumbers: HelplineContact[];
  source: string;
  sourceUrl: string;
  primaryRiver: string;
  stationIds: string[];
  reservoirIds: string[];
  imageUrl: string;
  imageAlt: string;
  imageCredit: string;
}

export interface LatestReadingData {
  value: number;
  recordedAt: string;
  unit: "meters" | "m3/s" | "mm";
  trend?: "rising" | "falling" | "steady";
  source: string;
  sourceUrl: string;
}

export interface GaugeStationData {
  id: string;
  name: string;
  districtId: string;
  riverName: string;
  state: "Bihar" | "Assam";
  latitude: number;
  longitude: number;
  dangerLevel: number;
  warningLevel: number;
  hfl: number; // Highest Flood Level in meters MSL
  hflDate: string; // Historical date/year of HFL record
  isGhat: boolean; // Flag marking designated Ghat station
  ghatName: string; // Dedicated Ghat name
  locationName?: string; // Municipality or locality
  source: string;
  sourceUrl: string;
  latestReading: LatestReadingData;
}

export interface ReservoirData {
  id: string;
  name: string;
  districtId: string;
  riverName: string;
  latitude: number;
  longitude: number;
  dangerLevel: number; // Full reservoir level (FRL)
  warningLevel: number; // Rule curve / flood warning level
  source: string;
  sourceUrl: string;
  latestReading: LatestReadingData;
}

// A community report as the district page shows it (read from Firestore `reports`)
export interface CitizenReportData {
  id: string;
  category:
    | "embankment_breach"
    | "waterlogging"
    | "river_overflow"
    | "evacuation_needed"
    | "road_submerged"
    | "dam_release"
    | "general_alert"
    | "other";
  description: string;
  photoUrl?: string;
  latitude: number;
  longitude: number;
  geohash: string;
  createdAt: string;
  confidence: number;
  districtId?: string;
}

export interface GaugeReadingHistoryPoint {
  id: string;
  value: number;
  recordedAt: string;
  timestampMs: number;
  source: string;
  sourceUrl: string;
}


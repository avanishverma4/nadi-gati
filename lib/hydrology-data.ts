/**
 * Converts a date stored in Firestore (Timestamp, {seconds}, ISO string or epoch ms) to an ISO
 * string, or null if it isn't a valid date. Seeded readings store Timestamps, which `new Date()`
 * cannot read, so every Firestore date must pass through here before reaching the UI.
 */
export function toIsoTimestamp(value: unknown): string | null {
  if (value === null || value === undefined || value === "") return null;
  const v = value as { toDate?: () => Date; seconds?: number };
  const date =
    typeof v.toDate === "function"
      ? v.toDate()
      : typeof v.seconds === "number"
        ? new Date(v.seconds * 1000)
        : new Date(value as string | number | Date);
  return Number.isNaN(date.getTime()) ? null : date.toISOString();
}

/**
 * True when a reading stored in Firestore is a water level in metres. An earlier ingestion job wrote
 * river flow (m³/s) into latestReading; such values must never be shown as a level or compared
 * with warning and danger marks.
 */
export function isLevelReading(reading: { unit?: string } | null | undefined): boolean {
  return Boolean(reading) && (!reading?.unit || reading.unit === "meters");
}

/**
 * The gauge that best represents a district's situation: the one standing highest relative to
 * its own danger mark (measured in warning-to-danger steps, so rivers of different sizes compare
 * fairly). Live values, when given, take precedence over the built-in readings.
 */
export function pickHeadlineStation(
  stationIds: string[],
  liveValues: Record<string, number> = {}
): { station: GaugeStationData; value: number } | undefined {
  let best: { station: GaugeStationData; value: number } | undefined;
  let bestScore = -Infinity;
  for (const id of stationIds) {
    const station = PILOT_GAUGE_STATIONS_DATA[id];
    if (!station) continue;
    const value = liveValues[id] ?? station.latestReading.value;
    const step = station.dangerLevel - station.warningLevel || 1;
    const score = (value - station.dangerLevel) / step;
    if (score > bestScore) {
      bestScore = score;
      best = { station, value };
    }
  }
  return best;
}


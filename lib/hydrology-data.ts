// Only numbers we can stand behind are shown. The per-district landlines and desk names above were
// never checked against an official list (several were 1077 under made-up desk names), so every
// district gets the same national and state toll-free numbers instead. To bring back a district
// line, check it against the district or SDMA website and add it here with its source.
function standardHelplines(state: DistrictData["state"]): HelplineContact[] {
  return [
    {
      title: "District emergency control room (toll-free)",
      number: "1077",
      type: "district_disaster_authority",
    },
    {
      title: `${state} state emergency operations centre (toll-free)`,
      number: "1070",
      type: "state_control_room",
    },
    { title: "National disaster helpline (NDMA)", number: "1078", type: "toll_free" },
    { title: "All emergencies: police, fire, ambulance", number: "112", type: "toll_free" },
  ];
}

for (const district of PILOT_DISTRICTS_DATA) {
  district.helplineNumbers = standardHelplines(district.state);
}


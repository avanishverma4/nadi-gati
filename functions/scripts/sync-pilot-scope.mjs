// Writes src/pilotScope.generated.ts from the website's pilot data (lib/hydrology-data.ts), so the
// scheduled ingestion jobs fetch data for exactly the districts and gauges the website shows.
// Runs before every build (npm run build, and so before every deploy). Needs Node 22.6 or later.
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "../../lib/hydrology-data.ts");
const target = path.resolve(here, "../src/pilotScope.generated.ts");

const web = await import(pathToFileURL(source).href);

const districts = web.PILOT_DISTRICTS_DATA.map((d) => ({
  id: d.id,
  name: d.name,
  state: d.state,
  latitude: d.latitude,
  longitude: d.longitude,
}));
const gauges = Object.values(web.PILOT_GAUGE_STATIONS_DATA).map((s) => ({
  id: s.id,
  name: s.name,
  districtId: s.districtId,
  riverName: s.riverName,
  latitude: s.latitude,
  longitude: s.longitude,
}));

const json = (value) => JSON.stringify(value, null, 2);
writeFileSync(
  target,
  `// Generated by functions/scripts/sync-pilot-scope.mjs from lib/hydrology-data.ts. Do not edit:
// change the website data and run \`npm run sync-scope\` (also runs before every build).
import { PilotScopeDistrict, PilotScopeGauge } from "./types";

export const PILOT_SCOPE_DISTRICTS: PilotScopeDistrict[] = ${json(districts)};

export const PILOT_SCOPE_GAUGES: PilotScopeGauge[] = ${json(gauges)};
`
);
console.info(
  `pilot scope: ${districts.length} districts, ${gauges.length} gauges -> ${path.relative(process.cwd(), target)}`
);
